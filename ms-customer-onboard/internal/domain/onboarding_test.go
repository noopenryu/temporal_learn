func TestOnboardingApplication_CalculateStepResultsAndProgress(t *testing.T) {
	app := &domain.OnboardingApplication{
		ID:                  uuid.New(),
		CustomerID:          "cust-1",
		Status:              domain.StatusDraft,
		WalletTierRequested: "TIER_1_BASIC",
		ExpiresAt:           time.Now().Add(24 * time.Hour),
	}

	t.Run("Empty application has 0% progress and cannot submit", func(t *testing.T) {
		res := app.CalculateStepResults()
		assert.Len(t, res, 5)

		assert.False(t, res[0].Completed) // personal info
		assert.False(t, res[1].Completed) // address info
		assert.False(t, res[2].Completed) // identity docs
		assert.False(t, res[3].Completed) // financial info
		assert.True(t, res[4].Completed)  // wallet tier is defaulted to TIER_1_BASIC

		assert.Equal(t, 20, app.ProgressPercentage()) // 1 out of 5 steps completed

		canSubmit, uncompleted := app.CanSubmit()
		assert.False(t, canSubmit)
		assert.NotEmpty(t, uncompleted)
	})

	t.Run("Filling all steps achieves 100% progress and allows submission", func(t *testing.T) {
		app.PersonalInfo = domain.PersonalInfo{
			FirstName:   "Alice",
			LastName:    "Smith",
			DateOfBirth: time.Now().AddDate(-25, 0, 0),
			Nationality: "SG",
			PhoneNumber: "+6591234567",
			Email:       "alice@example.com",
		}

		app.AddressInfo = domain.AddressInfo{
			Country:       "SG",
			City:          "Singapore",
			StreetAddress: "1 Raffles Place",
			PostalCode:    "048616",
		}

		app.IdentityDocs = domain.IdentityDocuments{
			DocumentType:     "PASSPORT",
			DocumentNumber:   "E12345678",
			IssuingCountry:   "SG",
			FrontDocumentURL: "https://storage/front.jpg",
			SelfieURL:        "https://storage/selfie.jpg",
		}

		app.FinancialInfo = domain.FinancialInfo{
			Occupation:    "Engineer",
			SourceOfFunds: "SALARY",
			AnnualIncome:  50000,
			DeclaredPEP:   false,
		}

		app.UpdateStepProgress()
		assert.Equal(t, 100, app.ProgressPercentage())
		assert.Len(t, app.CompletedSteps, 5)
		assert.Equal(t, "review_and_submit", app.CurrentStep)

		canSubmit, uncompleted := app.CanSubmit()
		assert.True(t, canSubmit)
		assert.Empty(t, uncompleted)
	})

	t.Run("Expired application cannot submit", func(t *testing.T) {
		app.ExpiresAt = time.Now().Add(-1 * time.Hour)
		assert.True(t, app.IsExpired())

		canSubmit, uncompleted := app.CanSubmit()
		assert.False(t, canSubmit)
		assert.Contains(t, uncompleted[0], "expired")
	})
}

func TestValidationFunctions(t *testing.T) {
	t.Run("ValidateStartRequest", func(t *testing.T) {
		assert.NoError(t, domain.ValidateStartRequest("cust-1", "user@test.com", "+123456789"))
		// Customer ID is optional and auto-generated by the backend
		assert.NoError(t, domain.ValidateStartRequest("", "user@test.com", "+123456789"))
		assert.Error(t, domain.ValidateStartRequest("cust-1", "invalid-email", "+123456789"))
		assert.Error(t, domain.ValidateStartRequest("cust-1", "user@test.com", ""))
	})

	t.Run("NormalizePhoneNumber", func(t *testing.T) {
		assert.Equal(t, "+15551234567", domain.NormalizePhoneNumber("+1 (555) 123-4567"))
		assert.Equal(t, "+6591234567", domain.NormalizePhoneNumber(" +65 9123-4567 "))
		assert.Equal(t, "0912345678", domain.NormalizePhoneNumber("0912-345-678"))
		assert.Equal(t, "", domain.NormalizePhoneNumber(""))
	})

	t.Run("GenerateCustomerID", func(t *testing.T) {
		id1 := domain.GenerateCustomerID()
		id2 := domain.GenerateCustomerID()
		assert.NotEmpty(t, id1)
		assert.NotEmpty(t, id2)
		assert.NotEqual(t, id1, id2)
		assert.True(t, len(id1) >= 8)
	})

	t.Run("ValidateIdentityDocs", func(t *testing.T) {
		validDoc := &domain.IdentityDocuments{
			DocumentType:     "NATIONAL_ID",
			DocumentNumber:   "123456789",
			IssuingCountry:   "VN",
			FrontDocumentURL: "https://url/front.jpg",
			SelfieURL:        "https://url/selfie.jpg",
		}
		assert.NoError(t, domain.ValidateIdentityDocs(validDoc))

		invalidType := *validDoc
		invalidType.DocumentType = "BUS_PASS"
		assert.Error(t, domain.ValidateIdentityDocs(&invalidType))

		missingFront := *validDoc
		missingFront.FrontDocumentURL = ""
		assert.Error(t, domain.ValidateIdentityDocs(&missingFront))
	})

	t.Run("ValidateWalletTier", func(t *testing.T) {
		assert.NoError(t, domain.ValidateWalletTier("TIER_1_BASIC"))
		assert.NoError(t, domain.ValidateWalletTier("tier_2_premium"))
		assert.Error(t, domain.ValidateWalletTier("TIER_3_UNSUPPORTED"))
	})
}
