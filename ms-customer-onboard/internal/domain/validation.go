package domain

import (
	"crypto/rand"
	"encoding/hex"
	"errors"
	"fmt"
	"net/mail"
	"strings"
	"time"
)

// Sentinel domain errors
var (
	ErrAlreadyOnboarded = errors.New("customer is already fully onboarded with an active wallet account")
)

// NormalizePhoneNumber strips non-numeric characters except leading +
func NormalizePhoneNumber(phone string) string {
	trimmed := strings.TrimSpace(phone)
	if trimmed == "" {
		return ""
	}

	var sb strings.Builder
	for i, r := range trimmed {
		if r == '+' && i == 0 {
			sb.WriteRune(r)
		} else if r >= '0' && r <= '9' {
			sb.WriteRune(r)
		}
	}
	return sb.String()
}

// GenerateCustomerID creates a new uniform customer ID
func GenerateCustomerID() string {
	b := make([]byte, 4)
	if _, err := rand.Read(b); err != nil {
		return fmt.Sprintf("CUST-%d", time.Now().UnixNano()%1000000)
	}
	return fmt.Sprintf("CUST-%s", strings.ToUpper(hex.EncodeToString(b)))
}

// ValidateStartRequest validates customer initialization data.
// customerID is optional and will be auto-generated by the system if empty.
func ValidateStartRequest(customerID, email, phone string) error {
	normalizedPhone := NormalizePhoneNumber(phone)
	if normalizedPhone == "" {
		return errors.New("phone_number is required")
	}
	if strings.TrimSpace(email) == "" {
		return errors.New("email is required")
	}
	if _, err := mail.ParseAddress(email); err != nil {
		return fmt.Errorf("invalid email format: %w", err)
	}
	return nil
}

// ValidatePersonalInfo validates customer personal information
func ValidatePersonalInfo(p *PersonalInfo) error {
	if strings.TrimSpace(p.FirstName) == "" {
		return errors.New("first_name is required")
	}
	if strings.TrimSpace(p.LastName) == "" {
		return errors.New("last_name is required")
	}
	if p.DateOfBirth.IsZero() {
		return errors.New("date_of_birth is required")
	}
	// Check sensible age bounds (e.g. between 0 and 120 years old)
	age := time.Now().Year() - p.DateOfBirth.Year()
	if age < 0 || age > 120 {
		return errors.New("date_of_birth must be a valid historical date")
	}
	if strings.TrimSpace(p.Nationality) == "" {
		return errors.New("nationality is required")
	}
	if strings.TrimSpace(p.PhoneNumber) == "" {
		return errors.New("phone_number is required")
	}
	if strings.TrimSpace(p.Email) == "" {
		return errors.New("email is required")
	}
	if _, err := mail.ParseAddress(p.Email); err != nil {
		return fmt.Errorf("invalid email format: %w", err)
	}
	return nil
}

// ValidateAddressInfo validates residential address information
func ValidateAddressInfo(a *AddressInfo) error {
	if strings.TrimSpace(a.Country) == "" {
		return errors.New("country is required")
	}
	if strings.TrimSpace(a.City) == "" {
		return errors.New("city is required")
	}
	if strings.TrimSpace(a.StreetAddress) == "" {
		return errors.New("street_address is required")
	}
	if strings.TrimSpace(a.PostalCode) == "" {
		return errors.New("postal_code is required")
	}
	return nil
}

// ValidateIdentityDocs validates identity verification documents
func ValidateIdentityDocs(d *IdentityDocuments) error {
	validTypes := map[string]bool{
		"NATIONAL_ID":     true,
		"PASSPORT":        true,
		"DRIVING_LICENSE": true,
	}
	d.DocumentType = strings.ToUpper(strings.TrimSpace(d.DocumentType))
	if !validTypes[d.DocumentType] {
		return errors.New("invalid document_type; supported values are NATIONAL_ID, PASSPORT, DRIVING_LICENSE")
	}
	if strings.TrimSpace(d.DocumentNumber) == "" {
		return errors.New("document_number is required")
	}
	if strings.TrimSpace(d.IssuingCountry) == "" {
		return errors.New("issuing_country is required")
	}
	if strings.TrimSpace(d.FrontDocumentURL) == "" {
		return errors.New("front_document_url is required")
	}
	if strings.TrimSpace(d.SelfieURL) == "" {
		return errors.New("selfie_url is required")
	}
	return nil
}

// ValidateFinancialInfo validates economic profile and PEP declaration
func ValidateFinancialInfo(f *FinancialInfo, tier string) error {
	if strings.TrimSpace(f.Occupation) == "" {
		return errors.New("occupation is required")
	}
	if strings.TrimSpace(f.SourceOfFunds) == "" {
		return errors.New("source_of_funds is required")
	}
	if tier == "TIER_2_PREMIUM" && f.AnnualIncome <= 0 {
		return errors.New("annual_income must be greater than 0 for TIER_2_PREMIUM")
	}
	return nil
}

// ValidateWalletTier validates requested wallet tier
func ValidateWalletTier(tier string) error {
	tier = strings.ToUpper(strings.TrimSpace(tier))
	if tier != "TIER_1_BASIC" && tier != "TIER_2_PREMIUM" {
		return errors.New("invalid wallet tier; must be TIER_1_BASIC or TIER_2_PREMIUM")
	}
	return nil
}
